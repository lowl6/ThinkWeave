class PromptTemplates:
    """所有AI调用的Prompt模板。集中管理便于A/B测试和迭代。"""

    # ---- 观点生成 ----

    BRAINSTORM = (
        "请围绕「{topic}」这一主题，产生 {count} 条独特、有创意的观点或想法。\n"
        "{context}\n"
        "请以编号列表形式输出，每条观点简洁明确（1-2句话）。"
    )

    LEAFHOPPER_EXPAND = (
        "研讨主题：{topic}\n\n"
        "这是第 {round} 轮接龙发散。基于以下已有观点：\n{parent_ideas}\n\n"
        "请从不同角度、跨领域地跳跃式发散出 {count} 条全新的想法。\n"
        "要求：不要重复已有观点，尽量从全新方向切入。\n"
        "请以编号列表形式输出。"
    )

    # ---- 观点精炼 ----

    REFINE_IDEAS = (
        "请将以下观点列表精炼为简洁的核心观点，每条不超过30字：\n\n"
        "{ideas}\n\n"
        "以编号列表格式输出。保持原意不变，只压缩表达。"
    )

    # ---- 语义聚类 ----

    SEMANTIC_CLUSTER = (
        "请将以下观点按语义相似度分组。给每组一个简短标签（2-6字）。\n\n"
        "{ideas}\n\n"
        "以JSON数组格式返回：\n"
        '[{{"label": "组标签", "indices": [0, 2, 5]}}]\n'
        "indices是观点编号（从0开始）。"
    )

    # ---- 相似度检测 ----

    DETECT_DUPLICATES = (
        "判断以下观点中哪些含义高度相似（相似度>85%）。\n\n"
        "{ideas}\n\n"
        "以JSON数组返回相似对：\n"
        '[{{"a": 0, "b": 3, "similarity": 0.92}}]\n'
        "如果没有相似对，返回空数组 []。"
    )

    MERGE_IDEAS = (
        "以下两条观点含义相似，请合并为一条更精炼的综合观点（不超过50字）：\n"
        "A: {idea_a}\n"
        "B: {idea_b}\n\n"
        "请直接输出合并后的观点，不要其他内容。"
    )

    # ---- 桶分类建议 ----

    BUCKET_CLASSIFY = (
        "以下是预定义的分类桶：\n{buckets}\n\n"
        "请将每条观点分配到最合适的桶中：\n{ideas}\n\n"
        '以JSON对象返回：{{"0": "桶A的label", "1": "桶B的label", ...}}\n'
        "key是观点编号（从0开始），value是桶的label。"
    )

    # ---- 投票分析 ----

    POLL_ANALYSIS = (
        "以下是关于「{topic}」的投票排名结果：\n{rankings}\n\n"
        "请分析：\n"
        "1. 团队共识：哪些观点获得最多支持？\n"
        "2. 分歧点：票数分布是否集中还是分散？\n"
        "3. 关键洞察：投票结果反映了什么趋势？\n"
        "4. 行动建议：基于投票结果的下一步建议。"
    )

    # ---- 流程设计 ----

    WORKFLOW_DESIGN = (
        "你是一个研讨流程设计专家。用户的研讨主题是：{topic}\n\n"
        "请基于 ThinkLets 方法论，设计一个包含3-5个环节的研讨流程。\n"
        "可用环节类型（必须从以下中选择）：\n"
        "- FreeBrainstorm: 自由头脑风暴（发散生成）\n"
        "- LeafHopper: 接龙发散（多轮跳跃式发散）\n"
        "- FastFocus: 快速聚焦（逐条表决Keep/Merge/Discard）\n"
        "- BucketWalk: 桶分类（预设分类桶，拖放归类）\n"
        "- PopcornSort: 米花拾掇（筛选+聚类+去重）\n"
        "- StrawPoll: 麦秆投票（分配点数投票排序）\n\n"
        "请为每个环节输出：type, title, duration_minutes, prompt\n"
        "以JSON数组格式返回。"
    )

    # ---- 全流程报告 ----

    FINAL_REPORT = (
        "你是一个研讨报告编写专家。以下是关于「{topic}」的研讨过程：\n\n"
        "{step_summaries}\n\n"
        "请生成一份结构化的研讨报告，包含：\n"
        "1. 研讨背景与目标\n"
        "2. 研讨方法与流程\n"
        "3. 关键发现（按优先级）\n"
        "4. 建议方案\n"
        "5. 结论\n\n"
        "使用Markdown格式。"
    )
